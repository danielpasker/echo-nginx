"""Merge the Trivy and Grype baseline reports into one triage table.

Usage (repo root):  python -I triage/triage.py
Writes triage/all-findings.csv and triage/summary.md.
"""
import csv
import json
from collections import Counter
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
BASELINE = ROOT / "baseline"
OUT = ROOT / "triage"

# Why each vulnerable package is in the image (from `apt-cache rdepends --installed`
# run inside nginx:1.25-bookworm). Anything not listed comes with the Debian base.
NGINX_LINKS = {"libssl3", "openssl", "libpcre2-8-0", "zlib1g"}
IMAGE_FILTER = {"libgd3", "libheif1", "libaom3", "libavif15", "libdav1d6", "libde265-0",
                "libabsl20220623", "libtiff6", "libjbig0", "libxpm4", "libx11-6",
                "libx11-data", "libfreetype6", "libpng16-16", "libexpat1", "libbrotli1"}
XSLT = {"libxslt1.1", "libxml2", "libicu72"}
CURL = {"curl", "libcurl4", "libnghttp2-14", "libssh2-1", "libldap-2.5-0", "libsasl2-2",
        "libsasl2-modules-db", "libgssapi-krb5-2", "libkrb5-3", "libk5crypto3",
        "libkrb5support0"}


def component(pkg):
    if pkg == "nginx":
        return "nginx"
    if pkg in NGINX_LINKS:
        return "linked by nginx"
    if pkg in IMAGE_FILTER:
        return "image-filter module deps"
    if pkg in XSLT:
        return "xslt module deps"
    if pkg in CURL:
        return "curl"
    return "debian base"


def method(row):
    comp, fixed = row["component"], row["fixed_version"]
    if comp == "nginx":
        return "backport-candidate"
    if row["package"] in ("libssl3", "openssl"):
        return "bump (static openssl in nginx)"
    if comp == "linked by nginx":
        return "bump-candidate (not chosen)" if fixed else "accept (no fix)"
    if fixed:
        return "base-refresh"
    if comp in ("image-filter module deps", "xslt module deps", "curl"):
        return "remove-candidate (kept for drop-in)"
    return "accept (no fix)"


def load():
    rows = {}

    def get(cve, pkg, version):
        return rows.setdefault((cve, pkg), {
            "cve": cve, "package": pkg, "installed": version, "fixed_version": "",
            "trivy_severity": "", "grype_severity": "", "trivy_status": "", "found_by": set()})

    trivy = json.loads((BASELINE / "baseline-trivy.json").read_text(encoding="utf-8"))
    for result in trivy["Results"]:
        for v in result.get("Vulnerabilities") or []:
            r = get(v["VulnerabilityID"], v["PkgName"], v["InstalledVersion"])
            r["trivy_severity"] = v["Severity"].capitalize()
            r["trivy_status"] = v.get("Status", "")
            r["fixed_version"] = v.get("FixedVersion") or r["fixed_version"]
            r["found_by"].add("trivy")

    grype = json.loads((BASELINE / "baseline-grype.json").read_text(encoding="utf-8"))
    for m in grype["matches"]:
        vuln, art = m["vulnerability"], m["artifact"]
        r = get(vuln["id"], art["name"], art["version"])
        r["grype_severity"] = vuln["severity"]
        r["fixed_version"] = r["fixed_version"] or ", ".join(vuln["fix"]["versions"])
        r["found_by"].add("grype")

    for r in rows.values():
        r["found_by"] = "+".join(sorted(r["found_by"]))
        r["component"] = component(r["package"])
        r["method"] = method(r)
    return sorted(rows.values(), key=lambda r: (r["component"], r["package"], r["cve"])), len(trivy["Results"][0]["Vulnerabilities"]), len(grype["matches"])


def main():
    rows, n_trivy, n_grype = load()
    cols = ["cve", "package", "installed", "fixed_version", "trivy_severity",
            "grype_severity", "trivy_status", "found_by", "component", "method"]
    with open(OUT / "all-findings.csv", "w", encoding="utf-8", newline="") as f:
        w = csv.DictWriter(f, fieldnames=cols, lineterminator="\n")
        w.writeheader()
        w.writerows(rows)

    def table(title, counter, n=None):
        lines = [f"### {title}", "", "| | count |", "|---|---|"]
        lines += [f"| {k} | {v} |" for k, v in counter.most_common(n)]
        return lines + [""]

    md = ["# Triage summary", "",
          "Generated by `triage/triage.py` from `baseline/`. Full list: `all-findings.csv`.", "",
          f"- Trivy findings: {n_trivy}",
          f"- Grype findings: {n_grype}",
          f"- Unique (CVE, package) pairs: {len(rows)}", ""]
    md += table("By method", Counter(r["method"] for r in rows))
    md += table("By component", Counter(r["component"] for r in rows))
    md += table("Found by", Counter(r["found_by"] for r in rows))
    md += table("Top 15 packages", Counter(r["package"] for r in rows), 15)
    md += ["### nginx findings", "", "| CVE | grype severity | found by |", "|---|---|---|"]
    md += [f"| {r['cve']} | {r['grype_severity']} | {r['found_by']} |"
           for r in rows if r["package"] == "nginx"]
    (OUT / "summary.md").write_text("\n".join(md) + "\n", encoding="utf-8", newline="\n")
    print(f"{len(rows)} rows -> triage/all-findings.csv, triage/summary.md")


if __name__ == "__main__":
    main()
