#!/usr/bin/env bash
# Package the compiled nginx into .deb files that mirror the upstream
# nginx.org packages (same paths, metadata and maintainer scripts).
set -euo pipefail

VERSION=1.25.5-1~bookworm+echo1          # "+echo1" sorts just above upstream's 1.25.5-1~bookworm
BASE=1.25.5
ARCH=$(dpkg --print-architecture)
MAINT="Danie Pasker <danielpasker123@gmail.com>"
SRC=/src/nginx                           # nginx source (conf/, html/)
PKG=/src/pkg-oss/debian/debian           # upstream packaging files
B=/build                                 # compiled trees from compile.sh
OUT=/out
mkdir -p "$OUT"

# copy a maintainer script, dropping the debhelper placeholder line
script() { sed '/#DEBHELPER#/d' "$1" > "$2"; chmod 755 "$2"; }

# remove debug symbols (-g) like upstream's dh_strip does; ~8 MB -> ~1.5 MB per binary
strip_bin() { strip --remove-section=.comment --remove-section=.note --strip-unneeded "$@"; }

# ---------------------------------------------------------------- nginx
R=$(mktemp -d)                           # staging root, mirrors /

install -d "$R"/usr/sbin "$R"/etc/nginx/conf.d "$R"/usr/lib/nginx/modules \
           "$R"/usr/share/nginx/html "$R"/var/cache/nginx "$R"/var/log/nginx \
           "$R"/etc/default "$R"/etc/init.d "$R"/etc/logrotate.d \
           "$R"/lib/systemd/system "$R"/usr/share/man/man8 "$R"/usr/share/lintian/overrides

# binaries
install -m 755 "$B"/nginx/objs/nginx       "$R"/usr/sbin/nginx
install -m 755 "$B"/nginx-debug/objs/nginx "$R"/usr/sbin/nginx-debug
strip_bin "$R"/usr/sbin/nginx "$R"/usr/sbin/nginx-debug

# config: nginx.conf + default.conf from pkg-oss, the rest from the nginx source
install -m 644 "$PKG"/nginx.conf         "$R"/etc/nginx/nginx.conf
install -m 644 "$PKG"/nginx.default.conf "$R"/etc/nginx/conf.d/default.conf
# -p keeps the tarball timestamps, so ETag/Last-Modified match the original
install -p -m 644 "$SRC"/conf/mime.types "$SRC"/conf/fastcgi_params \
               "$SRC"/conf/scgi_params "$SRC"/conf/uwsgi_params "$R"/etc/nginx/
ln -s /usr/lib/nginx/modules "$R"/etc/nginx/modules

# default web pages
install -p -m 644 "$SRC"/html/index.html "$SRC"/html/50x.html "$R"/usr/share/nginx/html/

# service files (unused in a container, shipped because the original has them)
sed -e 's/%%PROVIDES%%/nginx/g' -e 's/%%DEFAULTSTART%%/2 3 4 5/g' -e 's/%%DEFAULTSTOP%%/0 1 6/g' \
    "$PKG"/nginx.init.in > "$R"/etc/init.d/nginx
sed -e 's/%%PROVIDES%%/nginx-debug/g' -e 's/%%DEFAULTSTART%%//g' -e 's/%%DEFAULTSTOP%%/0 1 2 3 4 5 6/g' \
    "$PKG"/nginx.init.in > "$R"/etc/init.d/nginx-debug
chmod 755 "$R"/etc/init.d/nginx "$R"/etc/init.d/nginx-debug
install -m 644 "$PKG"/nginx.default       "$R"/etc/default/nginx
install -m 644 "$PKG"/nginx-debug.default "$R"/etc/default/nginx-debug
install -m 644 "$PKG"/nginx.service       "$R"/lib/systemd/system/nginx.service
install -m 644 "$PKG"/nginx-debug.service "$R"/lib/systemd/system/nginx-debug.service
install -m 644 "$PKG"/nginx.logrotate     "$R"/etc/logrotate.d/nginx

# man page (generated by the build) and lintian override
gzip -9n < "$B"/nginx/objs/nginx.8 > "$R"/usr/share/man/man8/nginx.8.gz
install -m 644 "$PKG"/nginx.lintian-overrides "$R"/usr/share/lintian/overrides/nginx

# package metadata, copied from the original nginx package
install -d "$R"/DEBIAN
cat > "$R"/DEBIAN/control <<EOF
Package: nginx
Version: $VERSION
Architecture: $ARCH
Maintainer: $MAINT
Section: httpd
Priority: optional
Depends: libc6 (>= 2.34), libcrypt1 (>= 1:4.1.0), libpcre2-8-0 (>= 10.22), zlib1g (>= 1:1.1.4), lsb-base (>= 3.0-6)
Recommends: logrotate
Provides: httpd, nginx, nginx-r$BASE
Conflicts: nginx-common, nginx-core
Replaces: nginx-common, nginx-core
Homepage: https://nginx.org
Description: high performance web server
 nginx [engine x] is an HTTP and reverse proxy server, as well as
 a mail proxy server. Rebuilt from source with CVE patches.
EOF
# files under /etc that dpkg must not overwrite if the user changed them
(cd "$R" && find etc -type f | sed 's|^|/|' | sort) > "$R"/DEBIAN/conffiles
for s in preinst postinst prerm postrm; do script "$PKG/nginx.$s" "$R/DEBIAN/$s"; done

dpkg-deb --root-owner-group --build "$R" "$OUT/nginx_${VERSION}_${ARCH}.deb"

# ---------------------------------------------------------------- modules
# module_pkg <name> <depends> <so files...>
module_pkg() {
    local name=$1 deps=$2; shift 2
    local R; R=$(mktemp -d)
    install -d "$R"/usr/lib/nginx/modules "$R"/DEBIAN
    for so in "$@"; do
        # shared libraries are 644 in Debian packages (not executable)
        install -m 644 "$B/modules/objs/$so"       "$R/usr/lib/nginx/modules/$so"
        install -m 644 "$B/modules-debug/objs/$so" "$R/usr/lib/nginx/modules/${so%.so}-debug.so"
    done
    strip_bin "$R"/usr/lib/nginx/modules/*.so
    cat > "$R"/DEBIAN/control <<EOF
Package: nginx-module-$name
Version: $VERSION
Architecture: $ARCH
Maintainer: $MAINT
Section: httpd
Priority: optional
Depends: $deps, nginx-r$BASE
Provides: nginx-module-$name-r$BASE
Homepage: https://nginx.org
Description: nginx $name dynamic module
 Rebuilt from source together with nginx.
EOF
    dpkg-deb --root-owner-group --build "$R" "$OUT/nginx-module-${name}_${VERSION}_${ARCH}.deb"
}

module_pkg geoip        "libc6 (>= 2.14), libgeoip1 (>= 1.6.12)" \
           ngx_http_geoip_module.so ngx_stream_geoip_module.so
module_pkg image-filter "libc6 (>= 2.14), libgd3 (>= 2.1.0~alpha~)" \
           ngx_http_image_filter_module.so
module_pkg xslt         "libc6 (>= 2.14), libxml2 (>= 2.7.4), libxslt1.1 (>= 1.1.25)" \
           ngx_http_xslt_filter_module.so

ls -l "$OUT"
